//
// mixed-script-token decides whether one URL host, URL segment, package name or
// config identifier mixes writing systems, and it decides that from these ranges
// alone. No \p{} escape runs in the engine, for the reason unicode-tabelas.mjs
// gives: CI runs Node 22 and this machine Node 24, and script data freezes per
// Node version, so a verdict computed with a property escape could differ
// between the two on the same blob.
//
// HOW IT WAS BUILT, once, by a script kept outside the repository, the way
// JUNCAO in unicode-tabelas.mjs was built:
//
//   - the letters are the code points where Alphabetic holds in the ICU of Node
//     v24.13.0 (ICU 77.1, Unicode 16.0);
//   - a letter that ScriptExtensions-17.0.0.txt (2025-08-01, 21:42:00 GMT,
//     sha256 ec2107e58825a1586acee8e0911ce18260394ac8b87e535ca325f1ccbeb06bc6)
//     lists takes the script set that file gives it (63 letters);
//   - every other letter takes its Script value from that same ICU. Scripts.txt
//     17.0.0 was not among the verified data files, so this is the JUNCAO
//     precedent and not a choice: a letter first assigned in 17.0 is absent,
//     and an absent letter is ignored, which can only make the rule quieter;
//   - Common, Inherited and Unknown are dropped, so a letter whose only script is
//     one of them is omitted (1,175 letters).
//
// 141,584 letters of 166 scripts, merged into 779 sorted, disjoint, inclusive
// [first, last, 'Xxxx Yyyy'] ranges, where the string is the set of four-letter
// script codes. prove-escritas.mjs holds the ICU-derived part against \p{} when it
// runs on Unicode 16.0, and skips with the version named otherwise.
//
